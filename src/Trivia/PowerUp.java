package Trivia;

/**
 * // -------------------------------------------------------------------------
/**
 *  Represents the different power-ups available in the trivia game.
 * 
 *  @author lenab
 *  @version Nov 8, 2026
 */
public enum PowerUp
{
    /**
     * Allows the player to skip a question
     */
    SKIP, 
   
    /**
     * Gives the player an extra life.
     */
    EXTRA_LIFE, 
    
    /**
     * Allows the player to double their points.
     */
    DOUBLE

}
